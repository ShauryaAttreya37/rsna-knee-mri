# %% [markdown]
# # RSNA Knee: Fold-0 Gold Overfit Gate & Sanity Check
#
# This notebook validates the complete end-to-end multi-series imaging training path:
# 1. **Environment & Hardware**: Confirms PyTorch, CUDA device capability, and GPU VRAM.
# 2. **Training Preflight**: Runs fail-fast verification across paths, manifests, and class coverage.
# 3. **Cohort Inspection**: Analyzes Fold 0 (12 class-complete gold studies).
# 4. **Tensor Caching**: Materializes geometrically sorted, full-FOV aspect-fitted $16 \times 224 \times 224$ series tensors.
# 5. **Gold Overfit Gate Execution**: Trains the multi-series model to memorize the cohort:
#    - $\text{BCE Loss} \le 0.05$
#    - $\text{Binary Accuracy} = 1.0\ (100\%)$
#    - $\text{Macro ROC AUC} \ge 0.99$
# 6. **Visual Analytics**: Plots loss, accuracy, and macro AUC progression across epochs.

# %%
import os
import sys
from pathlib import Path

os.environ["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"

# Paths
PROJECT_ROOT = Path(os.environ.get("RSNA_PROJECT_ROOT", "/home/shaurya/rsna-project")).expanduser()
DATA_ROOT = Path(os.environ.get("RSNA_DATA_ROOT", "/home/shaurya/rsna-data")).expanduser()
COMPETITION_ROOT = DATA_ROOT / "raw" / "competition"
FOLDS_PATH = DATA_ROOT / "manifests" / "gold_folds_v1" / "gold_folds.csv"
EXCLUSIONS_PATH = DATA_ROOT / "manifests" / "pixel_integrity_v1" / "excluded_series.csv"
CACHE_ROOT = DATA_ROOT / "processed" / "gold_overfit_cache_v1"
OUTPUT_ROOT = DATA_ROOT / "models" / "gold_overfit_v1"
REPORT_OUTPUT = PROJECT_ROOT / "reports" / "training" / "gold_overfit_summary.json"

sys.path.insert(0, str(PROJECT_ROOT / "src"))

import torch
import numpy as np
import matplotlib.pyplot as plt

print(f"PyTorch version : {torch.__version__}")
print(f"CUDA Available  : {torch.cuda.is_available()}")
if torch.cuda.is_available():
    print(f"Device Name     : {torch.cuda.get_device_name(0)}")
    print(f"Total VRAM      : {torch.cuda.get_device_properties(0).total_memory / (1024**3):.2f} GiB")
else:
    print("WARNING: CUDA is not available. Ensure you selected the 'rsna-train' kernel.")

# %% [markdown]
# ## 1. Run Automated Training Preflight
#
# Validates directory isolation, manifests, dependency locks, CUDA computation, and fold-0 class coverage before reading any DICOM pixel data.

# %%
from rsna.training_preflight import run_training_preflight

device = "cuda" if torch.cuda.is_available() else "cpu"
preflight = run_training_preflight(
    project_root=PROJECT_ROOT,
    competition_root=COMPETITION_ROOT,
    folds_path=FOLDS_PATH,
    exclusions_path=EXCLUSIONS_PATH,
    cache_root=CACHE_ROOT,
    output_root=OUTPUT_ROOT,
    device=device,
    fold=0,
    prepare_directories=True,
)

for check in preflight.checks:
    tag = "[PASS]" if check.status == "pass" else f"[{check.status.upper()}]"
    print(f"{tag:7s} {check.name:22s}: {check.detail}")

assert preflight.ready, "Preflight checks failed! Check the output above."
print("\n>>> All preflight gates PASSED successfully! <<<")

# %% [markdown]
# ## 2. Inspect Fold-0 Training Cohort
#
# Fold 0 was generated by deterministic multilabel stratification to ensure all 12 abnormalities have both positive and negative cases.

# %%
from rsna.training_data import load_gold_training_cohort
from rsna.submission import TARGET_COLUMNS

cohort = load_gold_training_cohort(
    competition_root=COMPETITION_ROOT,
    folds_path=FOLDS_PATH,
    exclusions_path=EXCLUSIONS_PATH,
    fold=0,
)

print(f"Cohort Fold          : {cohort.fold}")
print(f"Number of Studies    : {len(cohort.studies)}")
total_series = sum(len(s.series) for s in cohort.studies)
print(f"Total Eligible Series: {total_series}")

label_matrix = np.array([s.labels for s in cohort.studies])
print("\nFold 0 Target Distribution:")
print("-" * 45)
for idx, target in enumerate(TARGET_COLUMNS):
    pos = int(np.sum(label_matrix[:, idx] == 1))
    neg = int(np.sum(label_matrix[:, idx] == 0))
    print(f"  {target:18s} | Pos: {pos:2d} | Neg: {neg:2d}")
print("-" * 45)

# %% [markdown]
# ## 3. Materialize and Inspect Tensor Cache
#
# Slices are:
# - Geometrically sorted along the consensus normal vector.
# - Sampled to 16 uniformly spaced slices.
# - Normalized by 1st/99th series percentiles.
# - Resized with physical aspect ratio preserved and padded symmetrically to $224 \times 224$ (zero anatomy cropped).

# %%
from rsna.training_data import materialize_gold_cache

cache = materialize_gold_cache(
    cohort,
    competition_root=COMPETITION_ROOT,
    cache_root=CACHE_ROOT,
    sampled_slices=16,
    output_size=224,
    progress=True,
)

print(f"\nCached Studies: {len(cache.studies)}")
print(f"Cache Hits    : {cache.cache_hits}")
print(f"Cache Misses  : {cache.cache_misses}")
print(f"Cache Size    : {cache.cache_bytes / (1024**2):.1f} MB")

# Inspect the first study and series
first_study = cache.studies[0]
first_tensor = np.load(first_study.tensor_paths[0])
print(f"\nFirst Series Tensor Shape: {first_tensor.shape} (slices, height, width)")
print(f"First Series Tensor Dtype: {first_tensor.dtype}")
print(f"Value Range              : [{first_tensor.min():.3f}, {first_tensor.max():.3f}]")

# %% [markdown]
# ### Quick Slice Visualization
# View representative slices from the first cached series:

# %%
fig, axes = plt.subplots(2, 4, figsize=(14, 7))
step = max(1, first_tensor.shape[0] // 8)
for i, ax in enumerate(axes.flat):
    slice_idx = min(i * step, first_tensor.shape[0] - 1)
    ax.imshow(first_tensor[slice_idx], cmap="gray")
    ax.set_title(f"Slice {slice_idx}")
    ax.axis("off")
plt.suptitle("Cached Series Slices (Full-FOV Aspect-Fitted)", fontsize=14)
plt.tight_layout()
plt.show()

# %% [markdown]
# ## 4. Run Gold Overfit Training Gate
#
# Trains the multi-series model to memorize fold 0.
# The gate requires:
# - **Loss** $\le 0.05$
# - **Binary Accuracy** $= 1.0$ (100%)
# - **Macro ROC AUC** $\ge 0.99$

# %%
from rsna.gold_overfit import run_gold_overfit

print("Launching Fold-0 Gold Overfit Training...")
summary = run_gold_overfit(
    competition_root=COMPETITION_ROOT,
    folds_path=FOLDS_PATH,
    exclusions_path=EXCLUSIONS_PATH,
    project_root=PROJECT_ROOT,
    cache_root=CACHE_ROOT,
    output_root=OUTPUT_ROOT,
    report_output=REPORT_OUTPUT,
    fold=0,
    epochs=200,
    learning_rate=3e-3,
    device_name=device,
    target_loss=0.05,
    target_accuracy=1.0,
    target_macro_auc=0.99,
)

print("\n" + "=" * 50)
print(f"Gate Status   : {summary['status'].upper()}")
final_m = summary["metrics"]["final"]
print(f"Final BCE Loss: {final_m['loss']:.6f} (Target <= 0.05)")
print(f"Final Accuracy: {final_m['binary_accuracy'] * 100:.2f}% (Target = 100%)")
print(f"Final Macro AUC: {final_m['macro_auc']:.4f} (Target >= 0.99)")
print(f"Runtime       : {summary['runtime']['elapsed_seconds']:.1f}s")
print("=" * 50)

# %% [markdown]
# ## 5. Plot Training Convergence Curves

# %%
history = summary["metrics"].get("history", [])
if history:
    epochs = [h["epoch"] for h in history]
    losses = [h["loss"] for h in history]
    accuracies = [h["binary_accuracy"] * 100 for h in history]
    aucs = [h["macro_auc"] for h in history]

    fig, axes = plt.subplots(1, 3, figsize=(18, 5))

    # Loss Curve
    axes[0].plot(epochs, losses, color="#d9534f", lw=2, marker="o", markersize=4, label="BCE Loss")
    axes[0].axhline(y=0.05, color="gray", linestyle="--", label="Threshold (<= 0.05)")
    axes[0].set_title("Training Loss Convergence", fontsize=13, fontweight="bold")
    axes[0].set_xlabel("Epoch")
    axes[0].set_ylabel("BCE Loss")
    axes[0].grid(True, alpha=0.3)
    axes[0].legend()

    # Accuracy Curve
    axes[1].plot(epochs, accuracies, color="#5cb85c", lw=2, marker="s", markersize=4, label="Accuracy (%)")
    axes[1].axhline(y=100.0, color="gray", linestyle="--", label="Threshold (100%)")
    axes[1].set_title("Binary Accuracy Progression", fontsize=13, fontweight="bold")
    axes[1].set_xlabel("Epoch")
    axes[1].set_ylabel("Accuracy (%)")
    axes[1].grid(True, alpha=0.3)
    axes[1].legend()

    # Macro AUC Curve
    axes[2].plot(epochs, aucs, color="#0275d8", lw=2, marker="^", markersize=4, label="Macro AUC")
    axes[2].axhline(y=0.99, color="gray", linestyle="--", label="Threshold (>= 0.99)")
    axes[2].set_title("Macro ROC AUC Progression", fontsize=13, fontweight="bold")
    axes[2].set_xlabel("Epoch")
    axes[2].set_ylabel("Macro AUC")
    axes[2].grid(True, alpha=0.3)
    axes[2].legend()

    plt.tight_layout()
    plt.show()
else:
    print("No history recorded.")
